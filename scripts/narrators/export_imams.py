#!/usr/bin/env python3
"""Writes the roster of the fourteen out for the Java side to read.

`imams.py` is the one place that says which kunya in a chain names which of them, and it is
reference knowledge rather than anything extracted — see its own docstring. The site needs
the same table: when an isnād ends without naming an Imam and the narration itself opens
«سمعت أبا عبد الله عليه السلام يقول», the Imam the report rests on is in the body, and the
chain panel has no way to say so.

Rather than keep a second roster in Java and watch the two drift, this generates one from
the first, with each man's slug read off the narrator index so a link lands on his page
instead of a redirect.

    python3 scripts/narrators/export_imams.py
"""
import json
import os
import sys
import urllib.request

W = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
sys.path.insert(0, f'{W}/scripts/narrators')
import imams  # noqa: E402

OUT = f'{W}/src/main/resources/data/imams.json'
HOST = os.environ.get("ES_HOST", "http://localhost:9200")


def slugs():
    """person_id → slug for the fourteen, from the index the pages are served from."""
    body = {"size": 40, "_source": ["person_id", "slug", "display_ar", "display_en"],
            "query": {"terms": {"person_id": [row["id"] for row in imams.ROSTER]}}}
    request = urllib.request.Request(f'{HOST}/rewayaat_narrators/_search',
                                     data=json.dumps(body).encode(),
                                     headers={"Content-Type": "application/json"})
    found = {}
    for hit in json.load(urllib.request.urlopen(request))["hits"]["hits"]:
        row = hit["_source"]
        found[row["person_id"]] = row.get("slug") or ""
    return found


def main():
    by_id = slugs()
    out = []
    for row in imams.ROSTER:
        out.append({"id": row["id"], "ordinal": row["ordinal"],
                    "nameAr": row["name_ar"], "nameEn": row["name_en"],
                    "slug": by_id.get(row["id"], ""),
                    "exact": row["exact"], "en": row.get("en", [])})
    missing = [row["id"] for row in out if not row["slug"]]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as handle:
        json.dump({"_note": "Generated by scripts/narrators/export_imams.py from imams.py. "
                            "Do not edit; edit the roster there.",
                   "imams": out}, handle, ensure_ascii=False, indent=2)
    print(f"wrote {len(out)} imams -> {OUT}")
    if missing:
        print(f"  no slug in the index for: {', '.join(missing)}")


if __name__ == "__main__":
    main()
